//! End-to-end test of the `macs3-rs callpeak` path: the derived flag parser ->
//! the shared library pipeline -> the three output files.
//!
//! This is the "Rust side" differential: it does not consult the oracle, but it
//! pins the CLI contract (a real invocation must produce `*.xls`,
//! `*.narrowPeak` and `*.summits.bed` with the expected shape) so a regression
//! in dispatch or in the flag->config mapping fails here rather than silently.

use macs_cli::{parse_flags, Options};

fn tmpdir(tag: &str) -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("macs3rs-cli-{tag}-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&d);
    std::fs::create_dir_all(&d).unwrap();
    d
}

/// Write a small, *realistic* fixture: two strong treatment clusters, with
/// control background spread genome-wide (as real MACS input is) but at much
/// lower density near the clusters, so every region has lambda > 0 and the fold
/// enrichment stays high enough to call peaks.
fn write_fixture(dir: &std::path::Path) -> (std::path::PathBuf, std::path::PathBuf) {
    let treat = dir.join("treat.bed");
    let ctrl = dir.join("ctrl.bed");
    let mut t = String::new();
    let mut c = String::new();
    // two strong treatment clusters
    for i in 0..40 {
        t.push_str(&format!("chr1\t{}\t{}\tr\t0\t+\n", 990 + i, 1000 + i));
        t.push_str(&format!("chr1\t{}\t{}\tr\t0\t-\n", 4990 + i, 5000 + i));
    }
    // control background: dense enough that lambda > 0 genome-wide, sparse at
    // the clusters so they stay enriched (2 reads per cluster vs 40 treatment)
    for i in 0..40 {
        c.push_str(&format!(
            "chr1\t{}\t{}\tr\t0\t+\n",
            20000 + i * 60,
            20060 + i * 60
        ));
    }
    c.push_str("chr1\t995\t1005\tr\t0\t+\n");
    c.push_str("chr1\t4995\t5005\tr\t0\t+\n");
    std::fs::write(&treat, t).unwrap();
    std::fs::write(&ctrl, c).unwrap();
    (treat, ctrl)
}

fn parse(args: &[&str]) -> Options {
    let argv: Vec<String> = args.iter().map(|s| s.to_string()).collect();
    parse_flags("callpeak", &argv).expect("callpeak args must parse")
}

#[test]
fn callpeak_writes_all_three_files_through_the_real_parser() {
    let dir = tmpdir("files");
    let (treat, ctrl) = write_fixture(&dir);
    let out = dir.join("out");
    let o = parse(&[
        "-t",
        treat.to_str().unwrap(),
        "-c",
        ctrl.to_str().unwrap(),
        "-f",
        "BED",
        "-g",
        "100000",
        "--nomodel",
        "--extsize",
        "200",
        "--outdir",
        out.to_str().unwrap(),
        "-n",
        "t1",
    ]);
    macs_cli::commands::callpeak::run(&o).expect("callpeak runs");

    let xls = std::fs::read_to_string(out.join("t1_peaks.xls")).expect("xls written");
    let np = std::fs::read_to_string(out.join("t1_peaks.narrowPeak")).expect("narrowPeak written");
    let sb = std::fs::read_to_string(out.join("t1_summits.bed")).expect("summits written");

    // XLS has the version banner and the column header
    assert!(
        xls.starts_with("# This file is generated by MACS version 3.0.5"),
        "xls banner"
    );
    assert!(xls.contains("abs_summit"), "xls header has abs_summit");
    // at least one data row on each output
    let xls_rows = xls
        .lines()
        .filter(|l| !l.starts_with('#') && !l.starts_with("chr\t"))
        .count();
    assert!(xls_rows >= 1, "at least one peak row, got {xls_rows}");
    assert!(!np.trim().is_empty(), "narrowPeak non-empty");
    assert!(!sb.trim().is_empty(), "summits non-empty");
    // narrowPeak is 10 columns, summits is 5
    let npline = np.lines().next().unwrap();
    assert_eq!(npline.split('\t').count(), 10, "narrowPeak is BED6+4");
    let sbline = sb.lines().next().unwrap();
    assert_eq!(sbline.split('\t').count(), 5, "summits is BED5");

    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn a_valid_choice_flag_is_accepted_by_the_derived_parser() {
    // F126: the matrix stores choices comma-separated; the parser must accept a
    // genuine member like `BED` rather than rejecting it.
    let dir = tmpdir("choice");
    let (treat, _ctrl) = write_fixture(&dir);
    let argv: Vec<String> = ["-t", treat.to_str().unwrap(), "-f", "BED"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    assert!(
        parse_flags("callpeak", &argv).is_ok(),
        "`-f BED` is a valid choice"
    );
    let bad: Vec<String> = ["-t", treat.to_str().unwrap(), "-f", "NOPE"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    assert!(
        parse_flags("callpeak", &bad).is_err(),
        "`-f NOPE` is rejected"
    );
    let _ = std::fs::remove_dir_all(&dir);
}

#[test]
fn missing_required_flags_are_usage_errors() {
    // no -t
    assert!(parse_flags("callpeak", &["-g".into(), "1000".into()]).is_err());
    // bad choice rejected with a usage error
    let e = parse_flags(
        "callpeak",
        &["-t".into(), "x".into(), "-f".into(), "ZZZ".into()],
    )
    .expect_err("bad choice");
    assert!(format!("{e}").contains("invalid choice"), "got: {e}");
}

#[test]
fn help_short_circuits_required_validation() {
    // argparse prints usage and exits 0 for --help even though -t/-g are required.
    let o = parse_flags("callpeak", &["--help".into()]).expect("--help parses");
    assert!(o.help, "help flag set");
    // ...but a real invocation without the required flags is still a usage error
    assert!(parse_flags("callpeak", &["-g".into(), "1000".into()]).is_err());
}

